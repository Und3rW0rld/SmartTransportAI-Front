export function getRecommendations(userId: string) {
  const prefs = userPreferences[userId] ?? ['cultura', 'naturaleza']
  return DESTINATIONS
    .map(d => ({
      ...d,
      score: d.tags.filter(t => prefs.includes(t)).length / d.tags.length,
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, 4)
}
